// Builds the static GitHub Pages demo into docs/: a copy of public/ with demo mode enabled
// (in-browser mock API, data kept in localStorage). All asset URLs in public/ are relative,
// so the result works from any sub-path such as /training-management-erp/.
// Usage: npm run build:demo
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const source = path.join(root, 'public');
const target = path.join(root, 'docs');

const SKIP = new Set([path.join(source, 'js', 'demo', 'package.json')]);

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    if (SKIP.has(src)) continue;
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dest);
    else fs.copyFileSync(src, dest);
  }
}

fs.rmSync(target, { recursive: true, force: true });
copyDir(source, target);

fs.writeFileSync(
  path.join(target, 'config.js'),
  '// Generated by `npm run build:demo`. Demo mode: the in-browser mock API replaces the REST API.\n' +
    "window.__APP_CONFIG__ = { demo: true, apiBase: 'api' };\n",
);
fs.writeFileSync(path.join(target, '.nojekyll'), '');

// Guard against absolute asset URLs, which would break under a sub-path.
const offenders = [];
(function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(p);
    else if (/\.(html|css|js)$/.test(entry.name)) {
      const text = fs.readFileSync(p, 'utf8');
      if (/(?:href|src)=["']\/(?!\/)/.test(text) || /url\(["']?\/(?!\/)/.test(text) || /from ['"]\//.test(text)) offenders.push(path.relative(root, p));
    }
  }
})(target);
if (offenders.length) {
  console.error(`Absolute URLs found (they break on sub-paths): ${offenders.join(', ')}`);
  process.exit(1);
}

const count = (function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? walk(path.join(dir, e.name)) : 1), 0);
})(target);
console.log(`Demo build written to docs/ (${count} files). Preview: npm run serve:demo`);
